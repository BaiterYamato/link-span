STATUS_ICONS = {"ok": "[ok]  ", "aviso": "[warn]", "falha": "[fail]"}


def _run_first_line(command: list[str]) -> str | None:
    try:
        result = subprocess.run(
            command, capture_output=True, text=True, timeout=30
        )
    except (OSError, subprocess.TimeoutExpired):
        return None
    if result.returncode != 0:
        return None
    lines = result.stdout.strip().splitlines()
    return lines[0] if lines else None


def _parse_version(text: str) -> tuple[int, ...] | None:
    match = re.search(r"(\d+(?:\.\d+)+)", text)
    if not match:
        return None
    return tuple(int(part) for part in match.group(1).split("."))


def _check_python() -> tuple[str, str, str]:
    version = platform.python_version()
    parsed = _parse_version(version) or ()
    if parsed >= (3, 11):
        return "ok", "Python", f"{version} (tomllib available for the validation fallback)"
    if parsed >= (3, 10):
        return (
            "aviso",
            "Python",
            f"{version}: the CLI works, but the validation fallback requires 3.11+",
        )
    return "falha", "Python", f"{version}: the CLI requires Python 3.10+"


def _check_git() -> tuple[str, str, str]:
    line = _run_first_line(["git", "--version"])
    if line is None:
        return "falha", "git", "not found on PATH"
    return "ok", "git", line


def _check_cmake() -> tuple[str, str, str]:
    line = _run_first_line(["cmake", "--version"])
    if line is None:
        return "falha", "CMake", "not found on PATH (>= 3.20 required)"
    parsed = _parse_version(line)
    if parsed is not None and parsed < (3, 20):
        return "falha", "CMake", f"{line}: the project requires >= 3.20"
    return "ok", "CMake", line


def _check_ninja() -> tuple[str, str, str]:
    line = _run_first_line(["ninja", "--version"])
    if line is None:
        return "aviso", "Ninja", "not found (recommended; alternative: the Visual Studio generator)"
    return "ok", "Ninja", f"version {line}"


def _check_compiler() -> tuple[str, str, str]:
    gpp = _run_first_line(["g++", "--version"])
    if gpp is not None:
        return "ok", "C++ compiler", gpp
    cl = _run_first_line(["cl"])
    if cl is not None:
        return "ok", "C++ compiler", cl
    return "aviso", "C++ compiler", "no g++/cl found on PATH"


