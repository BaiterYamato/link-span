def cmd_test(args: argparse.Namespace) -> int:
    runner = find_repo_tool("shiplua_mod_test_runner", "SHIPLUA_MOD_TEST_RUNNER")
    if runner is None:
        print("Error: shiplua_mod_test_runner not found.", file=sys.stderr)
        print(
            "The mod test runner (mock runtime) is built from the Link-Span "
            "repository and must be compiled before use.",
            file=sys.stderr,
        )
        print("Build the runner with:", file=sys.stderr)
        print("  cmake --build build --target shiplua_mod_test_runner", file=sys.stderr)
        print(
            "Or point to an existing executable with the "
            "SHIPLUA_MOD_TEST_RUNNER environment variable.",
            file=sys.stderr,
        )
        return EXIT_MISSING_TOOL

    command = [str(runner), args.caminho]
    if args.game:
        command += ["--game", args.game]
    for capability in args.capability:
        command += ["--capability", capability]
    return _run_delegated(command)


