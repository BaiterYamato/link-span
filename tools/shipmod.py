def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="shipmod",
        description="Link-Span mod development CLI: create, validate and test mods.",
        epilog="Guide: https://github.com/BaiterYamato/link-span/blob/main/docs/shipmod-cli.md",
    )
    parser.add_argument("--version", action="version", version="%(prog)s 0.1.0-alpha.1")
    subparsers = parser.add_subparsers(dest="comando", required=True, metavar="command")

    p_new = subparsers.add_parser("new", help="create a new mod scaffold")
    p_new.add_argument("nome", metavar="name", help="mod folder name (slug, e.g. kafei-puppet)")
    p_new.add_argument("--dir", default=".", help="parent folder (default: current folder)")
    p_new.add_argument("--id", help="mod id (default: community.<name_with_underscores>)")
    p_new.add_argument("--author", "--autor", dest="autor",
                       help="mod author (default: git user.name)")
    p_new.add_argument("--description", "--desc", dest="desc", help="short mod description")
    p_new.set_defaults(func=cmd_new)

    p_validate = subparsers.add_parser(
        "validate", help="validate a mod manifest (folder, manifest.toml, .zip or .shipmod)"
    )
    p_validate.add_argument("caminhos", metavar="path", nargs="+", help="paths to validate")
    p_validate.set_defaults(func=cmd_validate)

    p_test = subparsers.add_parser(
        "test", help="run the mod's tests in the mock runtime"
    )
    p_test.add_argument("caminho", metavar="path", help="mod folder or .zip/.shipmod package")
    p_test.add_argument("--game", choices=sorted(GAMES), help="game simulated by the mock")
    p_test.add_argument(
        "--capability",
        action="append",
        default=[],
        help="extra capability granted to the mock (repeatable)",
    )
    p_test.set_defaults(func=cmd_test)

    p_doctor = subparsers.add_parser(
        "doctor",
        help="diagnoses the environment; with paths, checks ABI, exports and imports of native mods",
    )
    p_doctor.add_argument(
        "caminhos", metavar="path", nargs="*", help="native mods to check (directory, .zip or .shipmod)"
    )
    p_doctor.add_argument(
        "--host", help="game executable, to check ABI 1.3 host_fingerprints"
    )
    p_doctor.set_defaults(func=cmd_doctor)

    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
