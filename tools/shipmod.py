def _validate_manifest_data(data: object, origem: str) -> list[str]:
    """Basic structural manifest check (fallback without the C++ validator)."""
    errors: list[str] = []
    if not isinstance(data, dict):
        return [f"{origem}: the root document must be a TOML table"]
    for field in MANIFEST_REQUIRED_FIELDS:
        value = data.get(field)
        if not isinstance(value, str) or not value.strip():
            errors.append(f"{origem}: required field '{field}' is missing or invalid")
    version = data.get("version")
    if isinstance(version, str) and version and not SEMVER.fullmatch(version):
        errors.append(f"{origem}: field 'version' is not SemVer ({version!r})")
    games = data.get("games")
    if games is not None:
        if not isinstance(games, list) or any(g not in GAMES for g in games):
            errors.append(f"{origem}: field 'games' must list only 'oot' and/or 'mm'")
    return errors


def _validate_basic(path: Path) -> tuple[bool, str]:
    """Validates a manifest, folder or package without the canonical validator."""
    if tomllib is None:
        return False, "the validation fallback requires Python 3.11+ (tomllib)"

    origem = str(path)
    if path.is_dir():
        manifest = path / "manifest.toml"
        if not manifest.is_file():
            return False, f"{origem}: folder without manifest.toml"
        raw = manifest.read_bytes()
    elif path.is_file() and path.suffix.lower() in (".zip", ".shipmod"):
        try:
            with zipfile.ZipFile(path) as archive:
                raw = archive.read("manifest.toml")
        except (OSError, KeyError, zipfile.BadZipFile) as exc:
            return False, f"{origem}: invalid package or no manifest.toml ({exc})"
    elif path.is_file():
        raw = path.read_bytes()
    else:
        return False, f"{origem}: path is missing or unreadable"

    try:
        data = tomllib.loads(raw.decode("utf-8"))
    except (tomllib.TOMLDecodeError, UnicodeDecodeError) as exc:
        return False, f"{origem}: TOML syntax error ({exc})"

    errors = _validate_manifest_data(data, origem)
    if errors:
        return False, "; ".join(errors)
    assert isinstance(data, dict)
    return True, f"id={data['id']}, version={data['version']}"


def _run_delegated(command: list[str]) -> int:
    """Runs a delegated tool and diagnoses executable load failures."""
    try:
        result = subprocess.run(command)
    except OSError as exc:
        print(f"Error running {Path(command[0]).name}: {exc}", file=sys.stderr)
        return EXIT_MISSING_TOOL
    if result.returncode not in (EXIT_OK, EXIT_FAILURE, EXIT_USAGE):
        print(
            f"Warning: {Path(command[0]).name} exited with code {result.returncode}; "
            "check that the toolchain runtime (e.g. the MinGW DLLs) is on PATH.",
            file=sys.stderr,
        )
    return result.returncode


def cmd_validate(args: argparse.Namespace) -> int:
    paths: list[str] = args.caminhos
    validator = find_repo_tool("shiplua_manifest_validator", "SHIPLUA_MANIFEST_VALIDATOR")
    if validator is not None:
        return _run_delegated([str(validator), *paths])

    print(
        "Warning: shiplua_manifest_validator not found; using the basic "
        "structural check.",
        file=sys.stderr,
    )
    print(
        "For canonical validation, build it: "
        "cmake --build build --target shiplua_manifest_validator",
        file=sys.stderr,
    )
    if tomllib is None:
        print("Error: the validation fallback requires Python 3.11+ (tomllib).", file=sys.stderr)
        return EXIT_MISSING_TOOL

    all_valid = True
    for raw_path in paths:
        ok, message = _validate_basic(Path(raw_path))
        if ok:
            print(f"Valid (basic check): {raw_path} — {message}")
        else:
            all_valid = False
            print(f"Invalid: {message}", file=sys.stderr)
    return EXIT_OK if all_valid else EXIT_FAILURE


